    /// A tap on a notice, or on its Allow or Deny: the page opens the pane and answers once it is on screen.
    func userNotificationCenter(_ center: UNUserNotificationCenter, didReceive response: UNNotificationResponse, withCompletionHandler done: @escaping () -> Void) {
        let info = response.notification.request.content.userInfo
        if let id = info["doriface-id"] as? String, let host = info["doriface-host"] as? String {
            let answer = ["allow", "deny"].first { $0 == response.actionIdentifier }
            let url = "/?notice=\(id)&host=\(host)" + (answer.map { "&answer=\($0)" } ?? "")
            NotificationCenter.default.post(name: .dorifaceNoticeTap, object: url)
        }
        done()
    }

    /// While the app is in front, a notice still shows: the host already skips the pane this device has focused.
    func userNotificationCenter(_ center: UNUserNotificationCenter, willPresent notification: UNNotification, withCompletionHandler done: @escaping (UNNotificationPresentationOptions) -> Void) {
        done([.banner, .sound])
    }

    func application(_ application: UIApplication,
                     configurationForConnecting connectingSceneSession: UISceneSession,
                     options: UIScene.ConnectionOptions) -> UISceneConfiguration {
        let config = UISceneConfiguration(name: "Default Configuration",
                                          sessionRole: connectingSceneSession.role)
        config.delegateClass = SceneDelegate.self

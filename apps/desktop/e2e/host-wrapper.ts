// The guard wrapper host every e2e app launch spawns (#2399). The app's LocalHost always passes the release relay
// (`--relay <release>`, apps/desktop/src/main/local-host.ts), so the wrapper starts the real host on a relay the run
// owns instead, records what it was given, and refuses to start a host on the release relay. The wrapper is generated
// at run time because the stand-in relay's URL and the record file belong to the run, like the pairing wrapper
// apps/desktop/e2e/pair-rig.ts writes.
import { chmodSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";

export interface HostWrapperOptions {
  /** The relay this run owns; the host the app starts dials this, never the release relay. */
  readonly standInRelay: string;
  /** The relay a release build dials, baked in so the wrapper can refuse it. */
  readonly releaseRelay: string;
  /** The host CLI the wrapper starts; DORIFACE_E2E_HOST_CLI in the app's env overrides it. */
  readonly hostCli: string;
  /** One JSON line per spawn: the relay the app gave and the one the host was started on. */
  readonly recordFile: string;
}

export function hostWrapperSource(options: HostWrapperOptions): string {
  return [
    "#!/usr/bin/env bun",
    "// Generated by apps/desktop/e2e/host-wrapper.ts (#2399): the host every e2e app launch spawns. The app always",
    "// passes the release relay; this wrapper starts the real host on the relay this run owns instead, records what it",
    "// was given, and refuses to start a host on the release relay.",
    'import { appendFileSync } from "node:fs";',
    "",
    "const STAND_IN = " + JSON.stringify(options.standInRelay) + ";",
    "const RELEASE = " + JSON.stringify(options.releaseRelay) + ";",
    "const HOST_CLI = " + JSON.stringify(options.hostCli) + ";",
    "const RECORDS = " + JSON.stringify(options.recordFile) + ";",
    "",
    "if (STAND_IN === RELEASE) {",
    "  console.error(`e2e host wrapper: refusing to start the host on the release relay ${STAND_IN} (#2399)`);",
    "  process.exit(2);",
    "}",
    'const cli = process.env["DORIFACE_E2E_HOST_CLI"] ?? HOST_CLI;',
    'if (cli === "") {',
    '  console.error("e2e host wrapper: no host CLI to start (DORIFACE_E2E_HOST_CLI is empty)");',
    "  process.exit(2);",
    "}",
    "const args = process.argv.slice(2);",
    "let given;",
    "const passed = [];",
    "for (let index = 0; index < args.length; index += 1) {",
    '  if (args[index] === "--relay") {',
    "    if (given === undefined) given = args[index + 1];",
    "    index += 1;",
    "    continue;",
    "  }",
    '  passed.push(args[index] ?? "");',
    "}",
    "appendFileSync(",
    "  RECORDS,",
    "  `${JSON.stringify({ givenRelay: given ?? null, startedOn: STAND_IN, pid: process.pid, at: Date.now() })}\n`,",
    ");",
    'const child = Bun.spawn([...(cli.endsWith(".ts") ? [Bun.which("bun") ?? "bun"] : []), cli, "--relay", STAND_IN, ...passed], {',
    '  stdin: "ignore",',
    '  stdout: "ignore",',
    '  stderr: "inherit",',
    "});",
    'for (const signal of ["SIGTERM", "SIGINT"] as const) process.on(signal, () => child.kill(signal));',
    "process.exit(await child.exited);",
    "",
  ].join("\n");
}

export function writeHostWrapper(path: string, options: HostWrapperOptions): void {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, hostWrapperSource(options), { mode: 0o755 });
  chmodSync(path, 0o755);
}

import { defaultKeymap } from "./defaults.ts";
import { HERDR_APP_COMMIT, HERDR_APP_FILE, herdrAppDefaults } from "./herdr-app-defaults.ts";
import { BROWSER_TAB_FALLBACK, HERDR_APP_DIFFERENCES } from "./herdr-app-parity.ts";
import type { Platform } from "./trigger.ts";

const TITLE: Readonly<Record<Platform, string>> = { mac: "macOS", other: "Linux and Windows" };

const cell = (text: string): string => `\`${text.replaceAll("|", "\\|")}\``;
const visible = (action: string): string => (action.startsWith("send:") ? JSON.stringify(action).slice(1, -1) : action);

function rows(platform: Platform): string[] {
  const keymap = defaultKeymap(platform);
  const differences = new Map(HERDR_APP_DIFFERENCES[platform].map((entry) => [entry.chord, entry]));
  return herdrAppDefaults(platform).map(({ chord, trigger, action }) => {
    const bound = keymap.get(trigger);
    const difference = differences.get(chord);
    const doriface = bound === action ? "same" : bound === undefined ? "unbound" : cell(visible(bound));
    const browser = BROWSER_TAB_FALLBACK[platform][chord] ?? "same";
    return `| ${cell(chord)} | ${cell(visible(action))} | ${doriface} | ${browser} | ${difference?.reason ?? ""} |`;
  });
}

/** docs/keymap-herdr-app.md: every herdr-app default and doriface's default binding for it, generated. */
export function herdrAppTable(): string {
  const sections = (["mac", "other"] as const).map((platform) =>
    [
      `## ${TITLE[platform]} (\`${HERDR_APP_FILE[platform]}\`)`,
      "",
      "| herdr-app chord | herdr-app action | Doriterm | Browser tab | Why it differs |",
      "| --- | --- | --- | --- | --- |",
      ...rows(platform),
    ].join("\n"),
  );
  return [
    "# Doriterm's keys against herdr-app's defaults",
    "",
    `Generated by \`bun apps/web/scripts/keymap-table.ts\` from herdr-app's \`defaults/\` at \`${HERDR_APP_COMMIT}\``,
    "(`apps/web/src/keys/herdr-app/`) and Doriterm's default keymap (`apps/web/src/keys/defaults.ts`). Do not edit by hand.",
    "",
    "**Doriterm** is what Doriterm's default keymap does with that chord: `same` is herdr-app's action. **Browser tab** is",
    "what to use in a plain browser tab, which keeps the chord for itself; the installed app (PWA) and the desktop app get",
    "every chord. Keys a person rebinds in Settings > Keybindings stay theirs.",
    "",
    ...sections.flatMap((section) => [section, ""]),
  ].join("\n");
}

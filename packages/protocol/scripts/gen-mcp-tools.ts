import { join } from "node:path";
import { isJsonObject, parseJson, type JsonObject, type JsonValue } from "../src/json.ts";
import { formatSource, SCHEMA_PATH } from "./gen-api.ts";
import { SchemaShapeError } from "./schema-to-ts.ts";

export const MCP_OUTPUT_PATH = join(import.meta.dirname, "..", "src", "__generated__", "mcp-tools.ts");

/**
 * herdr-core methods that are no MCP tool: four that MCP's request and response cannot carry (a handshake, the schema
 * itself, and two that open a byte stream), and three that take the core or a machine away from its owner.
 */
export const EXCLUDED_METHODS = [
  "hello",
  "rpc.discover",
  "terminal.attach",
  "events.subscribe",
  "server.stop",
  "server.restart",
  "machine.rm",
] as const;

const COMPONENT_REF = /^#\/components\/schemas\/(.+)$/;

const object = (value: JsonValue | undefined): JsonObject => {
  if (!isJsonObject(value)) throw new SchemaShapeError(`expected an object, got ${JSON.stringify(value)}`);
  return value;
};

/** A copy of `node` whose component references point into `$defs`, adding each referenced name to `seen`. */
function rewriteRefs(node: JsonValue, seen: Set<string>): JsonValue {
  if (Array.isArray(node)) return node.map((item) => rewriteRefs(item, seen));
  if (!isJsonObject(node)) return node;
  const out: Record<string, JsonValue> = {};
  for (const [key, value] of Object.entries(node)) {
    const ref = key === "$ref" && typeof value === "string" ? COMPONENT_REF.exec(value) : null;
    if (ref?.[1] === undefined) out[key] = rewriteRefs(value, seen);
    else {
      seen.add(ref[1]);
      out[key] = `#/$defs/${ref[1]}`;
    }
  }
  return out;
}

/** One method's params as a self-contained JSON Schema object: its properties, required names and the $defs they use. */
export function inputSchemaOf(method: JsonObject, components: JsonObject): JsonObject {
  const seen = new Set<string>();
  const properties: Record<string, JsonValue> = {};
  const required: string[] = [];
  for (const param of Array.isArray(method["params"]) ? method["params"] : []) {
    const entry = object(param);
    const name = entry["name"];
    if (typeof name !== "string") throw new SchemaShapeError("a param without a name");
    const schema = object(entry["schema"]);
    const described =
      schema["description"] === undefined && typeof entry["description"] === "string"
        ? { ...schema, description: entry["description"] }
        : schema;
    properties[name] = rewriteRefs(described, seen);
    if (entry["required"] === true) required.push(name);
  }
  const defs: Record<string, JsonValue> = {};
  for (const name of seen) {
    if (name in defs) continue;
    const component = components[name];
    if (component === undefined) throw new SchemaShapeError(`unknown component ${name}`);
    defs[name] = rewriteRefs(component, seen);
  }
  return {
    type: "object",
    properties,
    ...(required.length > 0 ? { required } : {}),
    additionalProperties: false,
    ...(seen.size > 0
      ? { $defs: Object.fromEntries([...seen].toSorted().map((name) => [name, defs[name] ?? null])) }
      : {}),
  };
}

export async function generateMcpTools(schemaText: string): Promise<string> {
  const schema = object(parseJson(schemaText));
  const components = object(object(schema["components"])["schemas"]);
  const excluded = new Set<string>(EXCLUDED_METHODS);
  const methods = Array.isArray(schema["methods"]) ? schema["methods"].map((method) => object(method)) : [];
  const rows = methods
    .filter((method) => typeof method["name"] === "string" && !excluded.has(method["name"]))
    .map((method) => {
      const name = String(method["name"]);
      const description = method["summary"] ?? method["description"] ?? "";
      return {
        name: name.replaceAll(".", "_"),
        method: name,
        description,
        inputSchema: inputSchemaOf(method, components),
      };
    });
  const source = [
    "// Generated by packages/protocol/scripts/gen-mcp-tools.ts from packages/protocol/schema/hc.openrpc.json.\n" +
      "// Do not edit: run `bun run --cwd packages/protocol gen:api` after updating the schema.",
    'import type { JsonObject } from "../json.ts";',
    'import type { HcMethod } from "./hc-api.ts";',
    "/** One herdr-core method as an MCP tool: its MCP name, the method it calls, and its input schema. */",
    "export interface McpToolRow {\n  readonly name: string;\n  readonly method: HcMethod;\n  readonly description: string;\n  readonly inputSchema: JsonObject;\n}",
    `/** herdr-core methods that are no MCP tool. */\nexport const MCP_EXCLUDED_METHODS = ${JSON.stringify(EXCLUDED_METHODS)} as const;`,
    `/** Every MCP tool, in the schema's order. */\nexport const MCP_TOOLS: readonly McpToolRow[] = ${JSON.stringify(rows)};`,
  ].join("\n\n");
  return formatSource(source, "mcp-tools.ts");
}

if (import.meta.main) {
  const generated = await generateMcpTools(await Bun.file(SCHEMA_PATH).text());
  if (process.argv.includes("--check")) {
    if ((await Bun.file(MCP_OUTPUT_PATH).text()) !== generated) {
      console.error(`${MCP_OUTPUT_PATH} is stale: run \`bun run --cwd packages/protocol gen:api\``);
      process.exitCode = 1;
    }
  } else {
    await Bun.write(MCP_OUTPUT_PATH, generated);
  }
}
